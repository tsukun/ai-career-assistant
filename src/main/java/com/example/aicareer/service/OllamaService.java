package com.example.aicareer.service;

import com.example.aicareer.dto.CareerResponse;
import com.example.aicareer.dto.FactExtractionResponse;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.ollama.api.OllamaChatOptions;
import org.springframework.stereotype.Service;

import java.util.List;

@Service
public class OllamaService {

    private final ChatClient chatClient;

    public OllamaService(ChatClient.Builder chatClientBuilder) {
        this.chatClient = chatClientBuilder.build();
    }

    /**
     * 通常のAI回答
     */
    public String ask(String prompt) {

        return chatClient
                .prompt()
                .user(prompt)
                .options(OllamaChatOptions.builder()
                        .disableThinking())
                .call()
                .content();
    }

    /**
     * CareerResponse形式でAIから回答を取得する。
     */
    public CareerResponse askJson(String prompt) {

        return chatClient
                .prompt()
                .user(prompt)
                .options(OllamaChatOptions.builder()
                        .disableThinking())
                .call()
                .entity(
                        CareerResponse.class,
                        ChatClient.EntityParamSpec::validateSchema
                );
    }

    /**
     * FactExtractionResponse形式で
     * 職務経歴書から事実だけを抽出する。
     */
    public FactExtractionResponse extractFacts(String career) {

        String prompt = """
                あなたは職務経歴書から「明記された事実だけ」を抽出するAIです。

                以下の職務経歴書を読み、
                書かれている情報を10個のカテゴリに分類してください。


                ==================================================
                【最重要ルール】
                ==================================================

                1. 職務経歴書に書かれている情報だけを使用してください。

                2. 推測は禁止です。

                3. 評価は禁止です。

                4. 書かれていない成果を追加してはいけません。

                5. 書かれていない役割を追加してはいけません。

                6. 書かれていない技術を追加してはいけません。

                7. 技術名から別の技術を推測してはいけません。

                8. 一般的なITエンジニアの経験を補完してはいけません。

                9. 原文に存在する情報は、可能な限り原文に近い表現で抽出してください。

                10. 「高い能力」「豊富な経験」「対応できる」などの評価表現を追加しないでください。


                ==================================================
                【重要：情報を落とさないでください】
                ==================================================

                職務経歴書の文章を最初から最後まで確認してください。

                特に以下のような情報を見落とさないでください。

                ・年
                ・期間
                ・技術名
                ・プログラミング言語
                ・フレームワーク
                ・製品名
                ・通信方式
                ・データ連携方式
                ・担当工程
                ・役割
                ・システム名
                ・プロジェクト名


                ==================================================
                【カテゴリ1：経験年数・経験期間】
                ==================================================

                「2013年より」
                「2015年から」
                「10年間」
                「3年間」
                「2020年～2023年」

                のような年・期間に関する記述を抽出してください。

                例えば、

                「2013年より医療システム開発に従事」

                と書かれている場合、

                「2013年より医療システム開発に従事」

                をexperienceYearsに入れてください。


                ==================================================
                【カテゴリ2：業務内容】
                ==================================================

                実際に行った業務を抽出してください。

                例：

                「既存システムの改修」
                「機能追加」
                「Webアプリケーション開発」
                「後輩の指導」

                などです。


                ==================================================
                【カテゴリ3：担当したシステム・プロジェクト】
                ==================================================

                開発対象となったシステムやアプリケーションを抽出してください。

                例：

                「病院向け感染管理支援システム」
                「電子カルテとの連携システム」

                などです。


                ==================================================
                【カテゴリ4：担当した工程】
                ==================================================

                原文に記載されている工程だけを抽出してください。

                例：

                「開発」
                「カスタマイズ」
                「テスト」
                「リリース」
                「保守」

                などです。


                ==================================================
                【カテゴリ5：使用した技術・言語・フレームワーク・製品】
                ==================================================

                原文に明記されている技術名をそのまま抽出してください。

                特に技術名を見落とさないでください。

                例えば原文に、

                「Java」
                「C#」
                「Windows Forms」
                「Struts」
                「Spring Boot」

                と書かれていれば、

                technologiesには必ず、

                「Java」
                「C#」
                「Windows Forms」
                「Struts」
                「Spring Boot」

                を入れてください。


                技術名から別の技術を推測してはいけません。

                例えば、

                「Spring Boot」

                と書かれていても、

                「Spring Framework」
                「REST API」
                「Docker」

                などを追加してはいけません。


                ==================================================
                【カテゴリ6：システム間連携・インターフェース方式】
                ==================================================

                システム間の連携方式や通信方式を抽出してください。

                例えば原文に、

                「DWH連携」
                「ソケット通信」
                「CSV連携」

                と書かれていれば、

                interfacesには必ず、

                「DWH連携」
                「ソケット通信」
                「CSV連携」

                を入れてください。


                「CSV連携」からAPI連携などを推測してはいけません。


                ==================================================
                【カテゴリ7：担当した役割】
                ==================================================

                原文に明記された役割だけを抽出してください。

                例えば、

                「コードレビューを担当」
                「後輩の指導を担当」

                などです。

                「リーダー」
                「プロジェクトマネージャー」
                「品質管理担当」

                などが書かれていない場合は追加してはいけません。


                ==================================================
                【カテゴリ8：明記された成果】
                ==================================================

                原文に具体的な成果が書かれている場合だけ抽出してください。

                例えば、

                「処理時間を30%削減した」

                のような記述です。

                成果が書かれていない場合は、

                []

                にしてください。


                ==================================================
                【カテゴリ9：明記された資格】
                ==================================================

                原文に資格が書かれている場合だけ抽出してください。

                例えば、

                「基本情報技術者」
                「AWS Certified Solutions Architect」

                などです。

                書かれていない場合は、

                []

                にしてください。


                ==================================================
                【カテゴリ10：明記されたチーム規模・人数】
                ==================================================

                原文にチーム人数やメンバー数が書かれている場合だけ抽出してください。

                例えば、

                「5名チーム」
                「開発メンバー10名」

                などです。

                書かれていない場合は、

                []

                にしてください。


                ==================================================
                【空配列について】
                ==================================================

                該当する情報が存在しないカテゴリは、

                []

                にしてください。

                「なし」
                「不明」
                「該当なし」

                などの文字を入れてはいけません。


                ==================================================
                【職務経歴書】
                ==================================================

                """ + career + """


                ==================================================
                【出力形式】
                ==================================================

                必ず以下のJSON形式だけを出力してください。

                {
                  "experienceYears": [],
                  "businessActivities": [],
                  "systems": [],
                  "processes": [],
                  "technologies": [],
                  "interfaces": [],
                  "roles": [],
                  "achievements": [],
                  "qualifications": [],
                  "teamSize": []
                }

                JSON以外の文章は禁止です。
                Markdownのコードブロックは禁止です。
                """;

        return chatClient
                .prompt()
                .user(prompt)
                .options(OllamaChatOptions.builder()
                        .disableThinking())
                .call()
                .entity(
                        FactExtractionResponse.class,
                        ChatClient.EntityParamSpec::validateSchema
                );
    }

    /**
     * FactExtractionResponseを
     * 分析AIへ渡すためのテキストへ変換する。
     */
    private String formatFacts(FactExtractionResponse facts) {

        StringBuilder result = new StringBuilder();

        appendFacts(
                result,
                "■ 経験年数・経験期間",
                facts.getExperienceYears()
        );

        appendFacts(
                result,
                "■ 業務内容",
                facts.getBusinessActivities()
        );

        appendFacts(
                result,
                "■ 担当したシステム・プロジェクト",
                facts.getSystems()
        );

        appendFacts(
                result,
                "■ 担当した工程",
                facts.getProcesses()
        );

        appendFacts(
                result,
                "■ 使用した技術・言語・フレームワーク・製品",
                facts.getTechnologies()
        );

        appendFacts(
                result,
                "■ システム間連携・インターフェース方式",
                facts.getInterfaces()
        );

        appendFacts(
                result,
                "■ 担当した役割",
                facts.getRoles()
        );

        appendFacts(
                result,
                "■ 明記された成果",
                facts.getAchievements()
        );

        appendFacts(
                result,
                "■ 明記された資格",
                facts.getQualifications()
        );

        appendFacts(
                result,
                "■ 明記されたチーム規模・人数",
                facts.getTeamSize()
        );

        return result.toString();
    }

    /**
     * 事実一覧をテキストへ追加する。
     */
    private void appendFacts(
            StringBuilder result,
            String title,
            List<String> facts
    ) {

        result.append(title).append("\n");

        if (facts == null || facts.isEmpty()) {
            result.append("該当情報なし\n\n");
            return;
        }

        for (String fact : facts) {

            if (fact == null || fact.isBlank()) {
                continue;
            }

            result.append("- ")
                    .append(fact)
                    .append("\n");
        }

        result.append("\n");
    }

    /**
     * 職務経歴書をAIで分析する。
     * 処理の流れ：
     * ① 職務経歴書から事実だけを構造化抽出
     * ② 抽出された事実だけを分析AIへ渡す
     * ③ CareerResponseとして取得
     */
    public CareerResponse analyzeCareer(String career) {

        // ==========================================
        // ① 事実抽出
        // ==========================================

        FactExtractionResponse facts = extractFacts(career);

        // ==========================================
        // ② 抽出結果を確認
        // ==========================================

        String factText = formatFacts(facts);

        System.out.println();
        System.out.println("==========================================");
        System.out.println("===== 抽出された事実 =====");
        System.out.println(factText);
        System.out.println("==========================");
        System.out.println();

        // ==========================================
        // ③ 抽出された事実だけを分析AIへ渡す
        // ==========================================

        String prompt = """
                あなたは日本語で転職活動を支援するAIアシスタントです。

                以下の「抽出された事実」だけを使用して、
                職務経歴を分析してください。


                ==================================================
                【最重要ルール】
                ==================================================

                使用してよい情報は、
                「抽出された事実」に書かれている情報だけです。

                元の職務経歴書を推測してはいけません。

                抽出された事実に存在しない情報を追加してはいけません。


                ==================================================
                【禁止事項】
                ==================================================

                ・経験していない技術を経験済みとして扱う
                ・記載されていない工程を追加する
                ・記載されていない役割を追加する
                ・記載されていない成果を追加する
                ・技術から別の能力を推測する
                ・一般的なITエンジニア経験を補完する
                ・根拠のない評価を追加する
                ・「高度なスキル」「非常に優れている」などと断定する
                ・「できる」「対応できる」などの能力を勝手に断定する


                ==================================================
                【抽出された事実】
                ==================================================

                """ + factText + """


                ==================================================
                【1. 職務経歴の要約】
                ==================================================

                抽出された事実だけを使用してください。

                簡潔にまとめてください。

                新しい経験や技術を追加しないでください。


                ==================================================
                【2. 技術的な強み】
                ==================================================

                必ず3件作成してください。

                抽出された事実の中から、
                転職活動でアピール材料にできる経験を選んでください。

                ただし、能力を推測してはいけません。

                例えば、

                「Spring Bootへの移行に携わった」

                という事実から、

                「Spring Bootへの移行経験がある」

                と表現することはできます。

                しかし、

                「Spring Bootに精通している」

                とは書いてはいけません。


                ==================================================
                【3. 面接でアピールすべきポイント】
                ==================================================

                必ず3件作成してください。

                抽出された事実だけを根拠にしてください。

                具体的なエピソードが抽出された事実に存在しない場合は、
                エピソードを勝手に作らないでください。

                その場合は、

                「面接では具体的な事例を説明できるよう準備する」

                のような準備事項として記述してください。


                ==================================================
                【4. 今後伸ばすべきスキル】
                ==================================================

                必ず3件作成してください。

                この項目では、
                現在経験していない技術を提案して構いません。

                ただし、現在の経験とのつながりを説明してください。

                必ず、

                「今後学ぶ」
                「今後伸ばす」
                「今後身につける」

                などの将来表現を使用してください。

                現在すでに経験しているような表現は禁止です。


                ==================================================
                【件数に関する重要ルール】
                ==================================================

                strengthsは必ず3件。

                interviewPointsは必ず3件。

                recommendedSkillsは必ず3件。

                1件だけにしてはいけません。

                2件で終了してはいけません。

                各配列には必ず3つの文字列を入れてください。


                ==================================================
                【最終チェック】
                ==================================================

                JSONを出力する前に確認してください。

                1. 抽出された事実にない経験を追加していない
                2. 抽出された事実にない技術を経験済みとして扱っていない
                3. 成果を作っていない
                4. 役割を作っていない
                5. 工程を作っていない
                6. 技術から能力を推測していない
                7. 現在の経験と将来のスキルを混同していない
                8. 自然な日本語になっている
                9. strengthsが3件ある
                10. interviewPointsが3件ある
                11. recommendedSkillsが3件ある


                ==================================================
                【出力形式】
                ==================================================

                必ず以下のJSON形式だけを出力してください。

                {
                  "summary": "職務経歴の要約",
                  "strengths": [
                    "技術的な強み1",
                    "技術的な強み2",
                    "技術的な強み3"
                  ],
                  "interviewPoints": [
                    "面接でアピールすべきポイント1",
                    "面接でアピールすべきポイント2",
                    "面接でアピールすべきポイント3"
                  ],
                  "recommendedSkills": [
                    "今後伸ばすべきスキル1",
                    "今後伸ばすべきスキル2",
                    "今後伸ばすべきスキル3"
                  ]
                }

                JSON以外の文章は禁止です。
                Markdownのコードブロックは禁止です。
                """;

        // ==========================================
        // ④ AI分析
        // ==========================================

        CareerResponse response = askJson(prompt);

        // ==========================================
        // ⑤ 分析結果を詳細表示
        // ==========================================

        System.out.println();
        System.out.println("==========================================");
        System.out.println("===== AI分析結果 =====");
        System.out.println("summary:");
        System.out.println(response.getSummary());

        System.out.println();
        System.out.println("strengths:");
        System.out.println(response.getStrengths());

        System.out.println();
        System.out.println("interviewPoints:");
        System.out.println(response.getInterviewPoints());

        System.out.println();
        System.out.println("recommendedSkills:");
        System.out.println(response.getRecommendedSkills());

        System.out.println("======================");
        System.out.println();

        return response;
    }
}